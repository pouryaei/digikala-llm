def find_review_issues(fields: tuple[tuple[str, str | None], ...]) -> dict[IssueRule, tuple[str, str, bool]]:
    """Return at most one observed clause per issue and review."""
    findings = {}
    for source, value in fields:
        if not value:
            continue
        for clause in CLAUSE_BREAK.split(value):
            phrase = normalize_persian(clause)
            if not phrase:
                continue
            for item in ISSUE_RULES:
                if item in findings and findings[item][2]:
                    continue
                if item.accepted_context and item.accepted_context.search(phrase):
                    continue
                for match in item.pattern.finditer(phrase):
                    if BEFORE_DENIAL.search(phrase[:match.start()]) or AFTER_DENIAL.match(phrase[match.end():]):
                        continue
                    findings[item] = (source, clause.strip(), True)
                    break
                else:
                    if source == "نکات منفی" and item.explicit_alias and item.explicit_alias.fullmatch(phrase):
                        findings.setdefault(item, (source, clause.strip(), False))
    return findings
