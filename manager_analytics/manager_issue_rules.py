"""Auditable Persian rules for identifying issues in review text."""

from __future__ import annotations

import re
from dataclasses import dataclass
from unicodedata import normalize


CHARACTERS = str.maketrans("يىك۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩٫", "ییک01234567890123456789.")
MARKS = re.compile(r"[\u0610-\u061a\u064b-\u065f\u0670\u06d6-\u06edـ]")
CLAUSE_BREAK = re.compile(r"[\s]*[\n\r؛،;,.!?؟|]+[\s]*|\b(?:ولی|اما|با این حال|در عوض)\b")
ADVERBS = r"(?: (?:خیلی|بسیار|نسبتا|زیاد|واقعا|اصلا|کمی|یکم|به شدت))* "
POOR = r"(?:بد|ضعیف|پایین|نامناسب|نامرغوب|افتضاح|متوسط|بی ?کیفیت)(?:ه|ی)?|(?:خوب|قابل قبول|مناسب) (?:نیست|نبود)"
SMALL = r"(?:کوچک|کوچیک|تنگ|ریز)(?:ه|تر|ی)?"
LARGE = r"(?:بزرگ|گشاد)(?:ه|تر|ی)?"
ABSENT = r"(?:ندار(?:د|ه|ند)|نداشت(?:ه|م|ند)?|نیست|نبود(?:ه)?|نمی ?ده)"
AFTER_DENIAL = re.compile(rf"^(?: (?:که|هم|اصلا|واقعا|زیاد|چندان)){{0,2}} (?:{ABSENT}|نشد(?:ه)?|نکرد(?:ه)?|نمی ?شه)\b")
BEFORE_DENIAL = re.compile(r"(?:^| )(?:بدون|بی هیچ|هیچ(?: گونه)?|رفع|جلوگیری از) $")
SUITS_USE = r" برای (?:[^ ]+ ){0,4}(?:خوبه|مناسبه|خوب (?:است|بود|هست)|مناسب (?:است|بود|هست))\b"


def normalize_persian(value: str) -> str:
    text = normalize("NFKC", value).translate(CHARACTERS).casefold()
    text = MARKS.sub("", text).replace("\u200c", " ").replace("\u200b", " ")
    return " ".join(text.split())


def qualified(subject: str, modifier: str = POOR) -> str:
    return rf"(?:{subject}){ADVERBS}(?:{modifier})"


@dataclass(frozen=True)
class IssueRule:
    label: str
    aspect: str | None
    pattern: re.Pattern[str]
    explicit_alias: re.Pattern[str] | None
    accepted_context: re.Pattern[str] | None


def rule(label: str, aspect: str | None, pattern: str, explicit: str = "", accepted: str = "") -> IssueRule:
    return IssueRule(
        label, aspect, re.compile(rf"(?<!\w)(?:{pattern})(?!\w)"),
        re.compile(rf"(?:{explicit})") if explicit else None,
        re.compile(accepted) if accepted else None,
    )


